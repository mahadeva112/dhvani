/** Dub languages that have examples. */
export const EXAMPLE_LANGUAGES = Object.keys(LANGUAGE_EXAMPLES);

/** Cues in one line, "|" between them, each quoted. */
const cueLine = (cues) => cues.map((text) => `"${text}"`).join(' | ');

/**
 * The examples for `targetLanguage` as a prompt section, or '' when it has
 * none. The same text for every batch of a language, so it can sit in the
 * part of the prompt a model can cache.
 */
export const examplesBlock = (targetLanguage) => {
  const set = LANGUAGE_EXAMPLES[String(targetLanguage || '').trim()];
  if (!set) return '';
  const lines = [
    `EXAMPLES IN ${targetLanguage.toUpperCase()}`,
    `How the approach above sounds in ${targetLanguage}. "|" separates cues. "Not this" keeps the English word order cue by cue; "This" says the whole sentence the way a ${targetLanguage} speaker would, then splits it over the same cues by their length. Learn the approach from them; never copy their words into the translation.`,
  ];
  set.pairs.forEach(([wrong, right], index) => {
    lines.push('', `${index + 1}. ${LESSONS[index]}`, `English: ${cueLine(SOURCES[index])}`, `Not this: ${cueLine(wrong)}`, `This: ${cueLine(right)}`);
  });
  for (const example of set.extra || []) {
    lines.push('', `English: ${cueLine(example.english)}`, `This: ${cueLine(example.right)}`);
  }
  return `${lines.join('\n')}\n`;
};
